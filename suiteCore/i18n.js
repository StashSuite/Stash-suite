  function tr(text) {
    const lang = getLang();
    if (lang === "ja" || !text) return text;
    const i = IDX[lang];
    if (i == null) return text;
    const trimmed = text.trim();
    if (!trimmed) return text;
    const hit = DICT[trimmed];
    if (hit && hit[i]) return text.replace(trimmed, hit[i]);

    // Dynamic patterns
    let m;
    if ((m = trimmed.match(/^開いた履歴（(\d+)件）$/))) return `${DICT["履歴"][i]} (${m[1]})`;
    if ((m = trimmed.match(/^並べて再生に戻る（(\d+)）$/))) return `${DICT["並べて再生"][i]} (${m[1]})`;
    if ((m = trimmed.match(/^タグの好み（(\d+)個）$/))) {
      const lbl = ["Tag Weights", "標籤權重", "标签权重", "태그 선호도"][i];
      return `${lbl} (${m[1]})`;
    }
    if ((m = trimmed.match(/^まとめ（(\d+)本）$/))) return `${DICT["まとめ"][i]} (${m[1]})`;
    if ((m = trimmed.match(/^(\d+(?:\.\d+)?)秒$/))) return `${m[1]}${UNIT_SEC[i]}`;
    if ((m = trimmed.match(/^(\d+)分前$/))) return `${m[1]}${UNIT_MIN_AGO[i]}`;
    if ((m = trimmed.match(/^(\d+)時間前$/))) return `${m[1]}${UNIT_HR_AGO[i]}`;
    if ((m = trimmed.match(/^(\d+)人$/))) return `${m[1]}`;
    if ((m = trimmed.match(/^(\d+)本$/))) return `${m[1]}${UNIT_SCENES[i]}`;
    if ((m = trimmed.match(/^(\d+)個$/))) return `${m[1]}${UNIT_ITEMS[i]}`;
    if ((m = trimmed.match(/^(\d+)枚$/))) return `${m[1]}${UNIT_PAGES[i]}`;
    if ((m = trimmed.match(/^(\d+)枚組$/))) return `${m[1]}${UNIT_DISC[i]}`;
    if ((m = trimmed.match(/^評価 ★(\d+(?:\.\d+)?)$/))) return `${DICT["評価"][i]} ★${m[1]}`;
    if ((m = trimmed.match(/^続き p\.(\d+)$/))) return `${DICT["続き"][i]} p.${m[1]}`;
    if ((m = trimmed.match(/^(.+?) で探す$/))) {
      const fmt = [`Search ${m[1]}`, `搜尋 ${m[1]}`, `搜索 ${m[1]}`, `${m[1]} 검색`][i];
      return fmt;
    }
    if ((m = trimmed.match(/^前回：(.+)$/))) {
      const p = ["Last: ", "上次：", "上次：", "이전: "][i];
      return p + m[1];
    }
    if ((m = trimmed.match(/^まとめ:(.+)$/))) return `${DICT["まとめ"][i]}: ${m[1]}`;
    if ((m = trimmed.match(/^制作\s+(.+)$/))) return `${DICT["スタジオ"][i]} ${m[1]}`;
    return text;
  }

