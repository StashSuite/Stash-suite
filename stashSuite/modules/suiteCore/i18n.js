  S.setLang = (v) => {
    try { localStorage.setItem(KEY, v); } catch {}
    translateAll();
  };
  S.t = tr;
  S.translateAll = translateAll;

  addEventListener("storage", (e) => {
    if (!e.key || e.key === KEY) translateAll();
  });
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", translateAll, { once: true });
  else translateAll();
