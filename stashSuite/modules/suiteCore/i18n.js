  const SKIP = ".video-title,.lc-title,.lc-code,.lc-studio,.lc-tagchip,.vsc-performer,.qgp-name,.qg-face-name,.qg-name,.qb-name,.shist-title,.gp-name,.lh-sfile-name,.lh-folderpath,.mv-title,.sp22-tc-msg,textarea,code,pre";

  function applyTitle(el) {
    if (!(el instanceof Element) || !el.hasAttribute("title")) return;
    const lang = getLang();
    const cur = el.getAttribute("title");
    if (!el.dataset.i18nTitle || (cur !== el.dataset.i18nTitle && cur !== el.dataset.i18nTitleOut)) {
      el.dataset.i18nTitle = cur;
    }
    const next = lang === "ja" ? el.dataset.i18nTitle : tr(el.dataset.i18nTitle);
    el.dataset.i18nTitleOut = next;
    if (cur !== next) el.setAttribute("title", next);
  }

  function applyElement(el) {
    if (!(el instanceof Element)) return;
    applyTitle(el);
    if (el.closest(SKIP)) return;
    const lang = getLang();
    if (el.hasAttribute("placeholder")) {
      const orig = el.dataset.i18nPh ?? el.getAttribute("placeholder");
      el.dataset.i18nPh = orig;
      const next = lang === "ja" ? orig : tr(orig);
      if (el.getAttribute("placeholder") !== next) el.setAttribute("placeholder", next);
    }
    if (el.tagName === "INPUT") return;
    for (const node of el.childNodes) {
      if (node.nodeType === 3) {
        const orig = node._i18nOrig ?? node.nodeValue;
        if (!node._i18nOrig && orig && orig.trim()) node._i18nOrig = orig;
        if (!node._i18nOrig) continue;
        const next = lang === "ja" ? node._i18nOrig : tr(node._i18nOrig);
        if (node.nodeValue !== next) node.nodeValue = next;
      } else if (node.nodeType === 1) {
        applyElement(node);
      }
    }
  }

  let raf = 0;
  let translating = false;
  function translateAll() {
    if (raf) return;
    raf = requestAnimationFrame(() => {
      raf = 0;
      translating = true;
      try {
        document.querySelectorAll(SCOPE).forEach(applyElement);
      } finally {
        translating = false;
      }
    });
  }

  // Translate any dynamic tooltip immediately on hover before the browser shows it
  document.addEventListener("mouseover", (e) => {
    if (getLang() === "ja" || !(e.target instanceof Element)) return;
    const t = e.target.closest("[title]");
    if (t) applyTitle(t);
  }, true);

  new MutationObserver((ms) => {
    if (translating || getLang() === "ja") return;
    for (const m of ms) {
      if (m.type === "attributes") {
        if (m.target instanceof Element && m.target.closest(SCOPE)) {
          translating = true;
          try { applyTitle(m.target); } finally { translating = false; }
        }
        continue;
      }
      if (m.type === "characterData") {
        const p = m.target.parentElement;
        if (p && !p.closest(SKIP) && p.closest(SCOPE)) {
          delete m.target._i18nOrig;
          translateAll();
          return;
        }
        continue;
      }
      for (const n of m.addedNodes) {
        if (n.nodeType === 1 && (n.matches?.(SCOPE) || n.closest?.(SCOPE) || n.querySelector?.(SCOPE))) {
          translateAll();
          return;
        }
      }
    }
  }).observe(document.documentElement, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["title", "placeholder"] });

